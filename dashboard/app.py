"""
RNA-seq Pipeline Results Dashboard
----------------------------------
A read-only viewer for outputs already generated by the Nextflow pipeline.
Does NOT run Nextflow and does NOT require HPC access - it just visualizes
files sitting in ../results_summary/ (see README for the full pipeline
run instructions, which do require HPC/SLURM/Apptainer access).

Run with: streamlit run dashboard/app.py
"""

import streamlit as st
import pandas as pd
from pathlib import Path

st.set_page_config(
    page_title="RNA-seq Pipeline Results",
    layout="wide",
    initial_sidebar_state="expanded",
)

# Resolve results_summary/ relative to this script, so it works regardless
# of the directory the user runs `streamlit run` from.
RESULTS_DIR = Path(__file__).parent.parent / "results_summary"


def missing_data_notice(path: Path):
    st.warning(
        f"Expected data not found at `{path}`. "
        "Make sure `results_summary/` is present alongside the `dashboard/` folder "
        "(see README for the expected repository layout)."
    )


# ---- Sidebar navigation ----
st.sidebar.title("RNA-seq Pipeline")
st.sidebar.caption(
    "Results viewer — does not run the pipeline or require HPC access. "
    "See README to run the actual pipeline on a SLURM/Apptainer cluster."
)

page = st.sidebar.radio(
    "Section",
    [
        "Overview",
        "Differential Expression",
        "Plots",
        "GO Enrichment",
        "Network Analysis",
        "Pipeline Execution Info",
    ],
)

# =====================================================================
# OVERVIEW
# =====================================================================
if page == "Overview":
    st.title("RNA-seq Variant Calling & DGE Pipeline")
    st.markdown(
        """
        This dashboard visualizes results from a Nextflow pipeline covering two branches:

        - **Variant calling**: GATK best-practices RNA-seq variant discovery, joint
          genotyping across samples, and functional annotation.
        - **Differential gene expression**: featureCounts → DESeq2 → GO enrichment →
          network visualization.

        Demonstrated on 4 samples (2 Alzheimer's disease, 2 aged control) from a
        public postmortem brain RNA-seq dataset
        ([GSE153873](https://www.ncbi.nlm.nih.gov/geo/query/acc.cgi?acc=GSE153873)).
        """
    )

    col1, col2, col3 = st.columns(3)

    results_csv = RESULTS_DIR / "deseq2" / "deseq2_results.csv"
    if results_csv.exists():
        df = pd.read_csv(results_csv, index_col=0)
        n_tested = len(df)
        n_sig = (df["padj"] < 0.05).sum()
        col1.metric("Genes tested", f"{n_tested:,}")
        col2.metric("Significant (padj < 0.05)", f"{n_sig:,}")
        col3.metric("% significant", f"{100 * n_sig / n_tested:.2f}%")
    else:
        missing_data_notice(results_csv)

    st.subheader("Pipeline DAG")
    dag_path = RESULTS_DIR / "pipeline_info" / "pipeline_dag.png"
    if dag_path.exists():
        st.image(str(dag_path), caption="Auto-generated by Nextflow (-with-dag)")
    else:
        missing_data_notice(dag_path)

# =====================================================================
# DIFFERENTIAL EXPRESSION
# =====================================================================
elif page == "Differential Expression":
    st.title("Differential Expression Results (DESeq2)")

    results_csv = RESULTS_DIR / "deseq2" / "deseq2_results.csv"
    if not results_csv.exists():
        missing_data_notice(results_csv)
    else:
        df = pd.read_csv(results_csv, index_col=0)
        df.index.name = "gene_id"
        df = df.reset_index()

        col1, col2 = st.columns([1, 2])
        with col1:
            padj_cutoff = st.slider("padj threshold", 0.0, 1.0, 0.05, 0.01)
        with col2:
            gene_search = st.text_input("Search gene ID (partial match)", "")

        filtered = df[df["padj"] < padj_cutoff]
        if gene_search:
            filtered = filtered[filtered["gene_id"].str.contains(gene_search, case=False, na=False)]

        filtered = filtered.sort_values("padj")

        st.caption(f"Showing {len(filtered):,} of {len(df):,} genes tested")
        st.dataframe(filtered, use_container_width=True, height=500)

        st.download_button(
            "Download filtered results as CSV",
            filtered.to_csv(index=False),
            file_name="deseq2_filtered_results.csv",
            mime="text/csv",
        )

# =====================================================================
# PLOTS
# =====================================================================
elif page == "Plots":
    st.title("DESeq2 Plots")

    plot_files = {
        "PCA": "deseq2_pca.png",
        "MA plot": "deseq2_ma_plot.png",
        "Volcano plot": "deseq2_volcano.png",
        "Heatmap (top 30 DE genes)": "deseq2_heatmap.png",
    }

    cols = st.columns(2)
    for i, (title, filename) in enumerate(plot_files.items()):
        path = RESULTS_DIR / "plots" / filename
        with cols[i % 2]:
            st.subheader(title)
            if path.exists():
                st.image(str(path), use_container_width=True)
            else:
                missing_data_notice(path)

# =====================================================================
# GO ENRICHMENT
# =====================================================================
elif page == "GO Enrichment":
    st.title("GO Enrichment (Biological Process)")

    go_csv = RESULTS_DIR / "go_enrichment" / "go_go_enrichment.csv"
    if not go_csv.exists():
        missing_data_notice(go_csv)
    else:
        df = pd.read_csv(go_csv, index_col=0)
        df = df.sort_values("p.adjust")

        st.caption(f"{len(df)} enriched GO terms (pvalueCutoff = 0.05)")
        st.dataframe(
            df[["Description", "GeneRatio", "FoldEnrichment", "pvalue", "p.adjust", "geneID"]],
            use_container_width=True,
            height=500,
        )

        st.subheader("Top term")
        if len(df) > 0:
            top = df.iloc[0]
            st.markdown(
                f"**{top['Description']}** — {top['GeneRatio']} genes, "
                f"padj = {top['p.adjust']:.2e}\n\n"
                f"Genes: `{top['geneID']}`"
            )

# =====================================================================
# NETWORK ANALYSIS
# =====================================================================
elif page == "Network Analysis":
    st.title("Network Analysis")
    st.markdown(
        """
        Gene-concept and enrichment-map network views, built from the GO enrichment
        results above. WGCNA (co-expression) and STRING-based protein-protein
        interaction networks were considered but not used — WGCNA needs substantially
        more samples than the 4 used here, and STRING requires a live API call that
        may not work on network-restricted HPC compute nodes.
        """
    )

    col1, col2 = st.columns(2)
    with col1:
        st.subheader("Gene-Concept Network")
        path = RESULTS_DIR / "network_plots" / "network_cnetplot.png"
        if path.exists():
            st.image(str(path), use_container_width=True)
        else:
            missing_data_notice(path)

    with col2:
        st.subheader("Enrichment Map")
        path = RESULTS_DIR / "network_plots" / "network_emapplot.png"
        if path.exists():
            st.image(str(path), use_container_width=True)
        else:
            missing_data_notice(path)

# =====================================================================
# PIPELINE EXECUTION INFO
# =====================================================================
elif page == "Pipeline Execution Info":
    st.title("Pipeline Execution Info")
    st.markdown(
        "Metadata from the actual Nextflow run that produced these results "
        "(auto-generated by Nextflow's `report`/`trace`/`dag` config)."
    )

    trace_path = RESULTS_DIR / "pipeline_info" / "execution_trace.txt"
    if trace_path.exists():
        st.subheader("Execution trace (per-process resource usage)")
        trace_df = pd.read_csv(trace_path, sep="\t")
        st.dataframe(trace_df, use_container_width=True, height=400)
    else:
        missing_data_notice(trace_path)

    report_path = RESULTS_DIR / "pipeline_info" / "execution_report.html"
    if report_path.exists():
        st.subheader("Full execution report")
        st.markdown(
            f"Open the full interactive Nextflow execution report directly: "
            f"`{report_path}`"
        )
        with open(report_path, "r", encoding="utf-8") as f:
            html_content = f.read()
        st.components.v1.html(html_content, height=800, scrolling=True)
    else:
        missing_data_notice(report_path)
